def main():
    here = os.path.dirname(os.path.abspath(__file__))
    data = dict(bpm=BPM, beat=BEAT, bar=BAR, duration=DURATION,
                montage=dict(t0=M0, t1=M1, beats=MONTAGE_BEATS, bpm0=M_BPM0, bpm1=M_BPM1,
                             plates=[dict(beat=b, t=MONTAGE_BEATS[b], key=k, label=l) for b, k, l in MONTAGE]),
                scenes=[dict(id=i, start=s, end=e) for i, s, e in SCENES], hits=HITS)
    with open(os.path.join(here, "timeline.json"), "w") as f:
        json.dump(data, f, indent=1)
    with open(os.path.join(here, "..", "timeline.js"), "w") as f:
        f.write("// generated by audio/timeline.py — do not edit by hand\n")
        f.write("window.EARTH_TIMELINE = " + json.dumps(data) + ";\n")
    print("montage bpm1 = %.2f" % M_BPM1)
    print("beats:", MONTAGE_BEATS)


if __name__ == "__main__":
    main()
