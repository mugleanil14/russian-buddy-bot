"""Single source of truth for every cut, hit and label time in EARTH, SO FAR.

Run:  python3 audio/timeline.py   → writes audio/timeline.json and timeline.js
Both the score (audio/score.py) and the picture (index.html) read these numbers,
so a cut can never drift from the music.
"""
import json, math, os

BPM = 96.0
BEAT = 60.0 / BPM          # 0.625 s
BAR = 4 * BEAT             # 2.5 s
DURATION = 120.0

# Human-montage accelerando: tempo ramps linearly so that exactly 28 beats
# fit between 75.0 s and 88.0 s ("NOW").
M0, M1, M_BEATS = 75.0, 88.0, 28
M_BPM0 = BPM
M_BPM1 = 2 * M_BEATS * 60.0 / (M1 - M0) - M_BPM0   # ≈ 162.46


def montage_beat_time(k):
    """Time of beat k (0..28) under the linear tempo ramp."""
    L = M1 - M0
    a = (M_BPM1 - M_BPM0) / (2 * L * 60.0)
    b = M_BPM0 / 60.0
    c = -k
    if abs(a) < 1e-12:
        return M0 - c / b
    tau = (-b + math.sqrt(b * b - 4 * a * c)) / (2 * a)
    return M0 + tau


MONTAGE_BEATS = [round(montage_beat_time(k), 4) for k in range(M_BEATS + 1)]

# Scenes (engine programs) — start/end in seconds.
